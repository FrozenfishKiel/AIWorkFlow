/**
 * Returns the display metadata for a task status so the UI can stay consistent
 * across task lists, cards, and detail headers.
 */
export function getTaskStatusMeta(status: TaskStatus): TaskStatusMeta {
  return STATUS_META[status];
}

/**
 * Determines whether a task is still active for polling and live refresh logic.
 */
export function isTaskActive(status: TaskStatus): boolean {
  return STATUS_META[status].isActive;
}

/**
 * Produces a compact label for the task source so the UI can show the
 * important part of each submission without dumping raw payloads.
 */
export function summarizeTaskContent(input: Pick<ApiTaskRecord, "input_type"> & { content?: string | null }) {
  if (!input.content) {
    return "No content";
  }

  if (input.input_type === "url") {
    try {
      const parsed = new URL(input.content);
      return parsed.hostname;
    } catch {
      return input.content;
    }
  }

  if (input.input_type === "file") {
    const normalized = input.content.replaceAll("\\", "/");
    return normalized.split("/").filter(Boolean).pop() ?? input.content;
  }

  const trimmed = input.content.trim();
  return trimmed.length > 80 ? `${trimmed.slice(0, 80)}...` : trimmed;
}

/**
 * Derives a stable task card title from the current backend payload without
 * inventing a separate title field before the API owns one.
 */
export function getTaskDisplayTitle(task: Pick<ApiTaskRecord, "input_type" | "content">): string {
  const summary = summarizeTaskContent(task);

  if (task.input_type === "text") {
    return summary === "No content" ? "Text task" : summary;
  }

  if (task.input_type === "url") {
    return summary === "No content" ? "URL task" : summary;
  }

  return summary === "No content" ? "File task" : summary;
}
