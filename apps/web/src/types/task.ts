export type TaskStatus =
  | "queued"
  | "parsing"
  | "understanding"
  | "retrieving"
  | "generating"
  | "review_pending"
  | "reviewing"
  | "approved"
  | "exporting"
  | "completed"
  | "failed"
  | "rejected";

export type TaskInputType = "text" | "file" | "url";

export type StatusTone = "neutral" | "info" | "warning" | "success" | "danger";

export interface TaskStatusMeta {
  /** Human readable status label used in task list and detail headers. */
  label: string;
  tone: StatusTone;
  description: string;
  isActive: boolean;
}

export interface UnderstandingResult {
  /** Reviewer-facing short summary for the parsed source input. */
  summary: string;
  /** Audiences inferred by the backend before generation starts. */
  audience: string[];
  /** Key points the pipeline wants the reviewer to keep in view. */
  key_points: string[];
  /** Risk flags the pipeline wants reviewers to inspect before approval. */
  risk_points: string[];
  /** Items that still need manual confirmation. */
  uncertain_items: string[];
  /** Input quality markers generated during parsing. */
  input_quality: {
    source_kind: string;
    quality_flags: string[];
    extracted_length: number;
    metadata?: {
      title?: string;
      extractor?: string;
      [key: string]: unknown;
    };
  };
}

export interface ApiRetrievalHit {
  /** Stable backend source identifier used for visible attribution. */
  source_id: string;
  /** Human-readable source title. */
  title: string;
  /** Supporting excerpt returned by retrieval. */
  snippet: string;
  /** Why this source was chosen for the task. */
  reason: string;
}

export interface ApiWorkflowResult {
  /** Draft content generated by the first async slice. */
  draft: string;
  /** Notes the reviewer should inspect before approving later slices. */
  review_notes: string[];
  /** Questions still left open for human confirmation. */
  open_questions: string[];
  /** Evidence items the generated result claims to rely on. */
  evidence_used: { source_id: string; title: string }[];
  /** Uncertainties carried through to review. */
  uncertainties: string[];
  /** Manual checks still expected from a reviewer. */
  manual_checks: string[];
  /** Summary of the context package assembled for generation. */
  context_summary: {
    selected_hit_count: number;
    context_sections: string[];
  };
  /** Human-readable trace of major pipeline decisions. */
  processing_trace: string[];
}

export interface ApiReviewSnapshot {
  /** Current human review decision state. */
  decision: "in_review" | "approved" | "rejected";
  /** Reviewer note explaining the current action. */
  reviewer_note?: string | null;
  /** Reason recorded when the task is rejected. */
  rejection_reason?: string | null;
  /** Explicit items the reviewer chose not to adopt. */
  not_adopted_items: string[];
  /** Reviewer replacement for understanding, when present. */
  edited_understanding?: UnderstandingResult | null;
  /** Reviewer replacement for retrieval hits, when present. */
  edited_retrieval_hits: ApiRetrievalHit[];
  /** Reviewer replacement for workflow result, when present. */
  edited_workflow_result?: ApiWorkflowResult | null;
}

export interface ApiApprovedSnapshot {
  understanding?: UnderstandingResult | null;
  retrieval_hits: ApiRetrievalHit[];
  workflow_result?: ApiWorkflowResult | null;
}

